# Build param dump table
rows = []
for var in VARIABLES:
    if var not in all_df.columns:
        continue
    s = var_stats(var)
    p = PARAM_INFO.get(var, {})
    row = {"variable": var}
    row.update(p)
    row.update(s)
    row["total_rows"] = TOTAL_ROWS
    row["sampling_interval_s"] = INTERVAL_S
    row["total_duration_hours"] = round(DURATION_HOURS, 2)
    row["n_series"] = 3
    row["series_ids"] = "node-a, node-b, node-c"
    rows.append(row)

param_df = pd.DataFrame(rows)
param_df.to_csv(OUT / "param_dump.csv", index=False)

