# We document based on what generate_server_data.py specifies AND what we observe.

def var_stats(col):
    v = all_df[col].values
    pct = np.percentile(v, [5, 25, 50, 75, 95])
    return dict(
        mean=round(float(v.mean()),6),
        std=round(float(v.std()),6),
        min=round(float(v.min()),6),
        q05=round(float(pct[0]),6),
        q25=round(float(pct[1]),6),
        q50=round(float(pct[2]),6),
        q75=round(float(pct[3]),6),
        q95=round(float(pct[4]),6),
        max=round(float(v.max()),6),
        zero_fraction=round(float((v==0).mean()),6),
        n_total=int(len(v)),
    )

