#!/usr/bin/env python3
"""
Example: Load synthetic PSI data and build pytorch-forecasting TimeSeriesDataSet
for training a TemporalFusionTransformer.

This script demonstrates how to:
1. Load train/val/test CSV files generated by generate_psi_7d.py
2. Parse metadata.json to understand column roles
3. Construct TimeSeriesDataSet with proper normalization and scaling
4. Create DataLoaders for training
"""

import json
from pathlib import Path

import pandas as pd
from pytorch_forecasting import TimeSeriesDataSet, TemporalFusionTransformer
from pytorch_forecasting.data import GroupNormalizer

# ============================================================================
# CONFIGURATION
# ============================================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data" / "synthetic"

METADATA_FILE = DATA_DIR / "metadata.json"
TRAIN_FILE = DATA_DIR / "train.csv"
VAL_FILE = DATA_DIR / "val.csv"
TEST_FILE = DATA_DIR / "test.csv"

MAX_ENCODER_LENGTH = 96  # ~24 minutes of history @ 15s interval
MAX_PREDICTION_LENGTH = 24  # ~6 minutes forecast horizon @ 15s interval

BATCH_SIZE = 32

# ============================================================================
# 1. LOAD METADATA
# ============================================================================

print("=" * 80)
print("STEP 1: LOAD METADATA")
print("=" * 80)

with open(METADATA_FILE) as f:
    metadata = json.load(f)

print(f"\nData origin: {metadata['data_origin']}")
print(f"Seed: {metadata['seed']}")
print(f"Days: {metadata['days']}")
print(f"Nodes: {metadata['nodes']}")
print(f"Spike threshold: {metadata['spike_threshold']}")

print("\nColumn roles:")
column_roles = metadata["column_roles"]
print(f"  Target: {column_roles['target']}")
print(f"  Group IDs: {column_roles['group_ids']}")
print(f"  Static categoricals: {column_roles['static_categoricals']}")
print(f"  Time-varying known reals: {column_roles['time_varying_known_reals']}")
print(f"  Time-varying unknown reals: {column_roles['time_varying_unknown_reals']}")

print("\nSplit statistics:")
for split_name, split_stats in metadata["split_stats"].items():
    print(f"  {split_name}:")
    print(f"    Rows: {split_stats['rows']:,}")
    print(f"    Spikes: {split_stats['spike_count']:,} ({split_stats['spike_pct']:.1f}%)")
    print(f"    Spike events: {split_stats['spike_events']}")

# ============================================================================
# 2. LOAD DATA
# ============================================================================

print("\n" + "=" * 80)
print("STEP 2: LOAD CSV FILES")
print("=" * 80)

train_df = pd.read_csv(TRAIN_FILE)
val_df = pd.read_csv(VAL_FILE)
test_df = pd.read_csv(TEST_FILE)

# Convert timestamps
for df in [train_df, val_df, test_df]:
    df["timestamp"] = pd.to_datetime(df["timestamp"])

print(f"\nTrain: {train_df.shape[0]:,} rows, {train_df['node_id'].nunique()} nodes")
print(f"Val:   {val_df.shape[0]:,} rows")
print(f"Test:  {test_df.shape[0]:,} rows")

# Verify data quality
print("\nData quality checks:")
for name, df in [("train", train_df), ("val", val_df), ("test", test_df)]:
    nan_count = df.isna().sum().sum()
    print(f"  {name}: {nan_count} NaNs")

# ============================================================================
# 3. CREATE TRAINING DATASET
# ============================================================================

print("\n" + "=" * 80)
print("STEP 3: CREATE TRAINING TIMESERIESDATASET")
print("=" * 80)

training_dataset = TimeSeriesDataSet(
    train_df,
    time_idx="time_idx",
    target=column_roles["target"],  # "psi_io_some_avg10"
    group_ids=column_roles["group_ids"],  # ["node_id"]
    max_encoder_length=MAX_ENCODER_LENGTH,
    max_prediction_length=MAX_PREDICTION_LENGTH,
    static_categoricals=column_roles["static_categoricals"],  # ["node_id", "workload_type"]
    time_varying_known_reals=column_roles["time_varying_known_reals"],
    time_varying_known_categoricals=[],
    time_varying_unknown_reals=column_roles["time_varying_unknown_reals"],
    target_normalizer=GroupNormalizer(groups=column_roles["group_ids"]),
    add_relative_time_idx=False,
    add_target_scales=True,  # Compute scale for each series
    allow_missing_timesteps=False,
)

print(f"\nTraining dataset created:")
print(f"  Samples: {len(training_dataset):,}")
sample = training_dataset[0]
if isinstance(sample, tuple):
    x, y = sample
    print(f"  x is dict: {isinstance(x, dict)}")
    print(f"  y shape: {y.shape if hasattr(y, 'shape') else 'N/A'}")
else:
    print(f"  Sample type: {type(sample)}")

# ============================================================================
# 4. CREATE VALIDATION DATASET
# ============================================================================

print("\n" + "=" * 80)
print("STEP 4: CREATE VALIDATION TIMESERIESDATASET")
print("=" * 80)

# Combine train + val for validation dataset
# (validation needs history from training data)
train_val_df = pd.concat([train_df, val_df], ignore_index=True).sort_values(
    ["node_id", "time_idx"]
).reset_index(drop=True)

validation_dataset = TimeSeriesDataSet.from_dataset(
    training_dataset,
    train_val_df,
    predict=True,  # For prediction mode
    stop_randomization=True,
    allow_missing_timesteps=True,  # Allow gaps between splits
)

print(f"\nValidation dataset created:")
print(f"  Samples: {len(validation_dataset):,}")

# ============================================================================
# 5. CREATE TEST DATASET
# ============================================================================

print("\n" + "=" * 80)
print("STEP 5: CREATE TEST TIMESERIESDATASET")
print("=" * 80)

# Combine train + val + test for test dataset
# (test predictions need history from all prior data)
train_val_test_df = pd.concat([train_df, val_df, test_df], ignore_index=True).sort_values(
    ["node_id", "time_idx"]
).reset_index(drop=True)

test_dataset = TimeSeriesDataSet.from_dataset(
    training_dataset,
    train_val_test_df,
    predict=True,
    stop_randomization=True,
    allow_missing_timesteps=True,  # Allow gaps between splits
)

print(f"\nTest dataset created:")
print(f"  Samples: {len(test_dataset):,}")

# ============================================================================
# 6. CREATE DATALOADERS
# ============================================================================

print("\n" + "=" * 80)
print("STEP 6: CREATE DATALOADERS")
print("=" * 80)

train_dataloader = training_dataset.to_dataloader(
    train=True,
    batch_size=BATCH_SIZE,
    num_workers=0,
)

val_dataloader = validation_dataset.to_dataloader(
    train=False,
    batch_size=BATCH_SIZE,
    num_workers=0,
)

test_dataloader = test_dataset.to_dataloader(
    train=False,
    batch_size=BATCH_SIZE,
    num_workers=0,
)

print(f"\nDataLoaders created:")
print(f"  Train: {len(train_dataloader)} batches")
print(f"  Val:   {len(val_dataloader)} batches")
print(f"  Test:  {len(test_dataloader)} batches")

# ============================================================================
# 7. INSPECT A BATCH
# ============================================================================

print("\n" + "=" * 80)
print("STEP 7: INSPECT A TRAINING BATCH")
print("=" * 80)

batch = next(iter(train_dataloader))
x, y = batch

print(f"\nBatch structure:")
print(f"  x (features): dict with {len(x)} keys")
print(f"  y (target): {type(y)}")

for key, val in x.items():
    if isinstance(val, dict):
        print(f"\n  x['{key}'] (dict):")
        for subkey, subval in val.items():
            print(f"    {subkey}: shape {subval.shape}, dtype {subval.dtype}")
    else:
        print(f"  x['{key}']: shape {val.shape}, dtype {val.dtype}")

# ============================================================================
# 8. SAMPLE USAGE FOR MODEL TRAINING
# ============================================================================

print("\n" + "=" * 80)
print("STEP 8: SAMPLE MODEL TRAINING SETUP")
print("=" * 80)

print("""
To train a TemporalFusionTransformer on this data, use:

    from pytorch_forecasting import TemporalFusionTransformer
    from pytorch_lightning import Trainer
    from pytorch_forecasting.metrics import QuantileLoss

    # Create model
    model = TemporalFusionTransformer.from_dataset(
        training_dataset,
        learning_rate=0.001,
        hidden_size=16,
        attention_head_size=2,
        dropout=0.1,
        loss=QuantileLoss(),
    )

    # Train
    trainer = Trainer(
        max_epochs=50,
        gpus=1 if torch.cuda.is_available() else 0,
        callbacks=[EarlyStopping(monitor="val_loss", patience=5)],
    )
    trainer.fit(model, train_dataloader, val_dataloader)

    # Predict
    predictions, x = model.predict(test_dataloader, return_x=True)
    
Expected results:
  - ~70-95% recall/precision on spike detection (realistic unpredictability)
  - Naive baseline achieves ~69% precision, 100% recall (intentionally not perfect)
  - Model should improve significantly with learning
""")

print("\n" + "=" * 80)
print("SUCCESS: TimeSeriesDataSet construction complete!")
print("=" * 80)
